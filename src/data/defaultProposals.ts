const makeInstallments = (
  type: Proposal['type'], 
  totalAmount: number, 
  status: Proposal['paymentTerms']['paymentStatus'] = 'odeme_bekliyor',
  customAdvanceRatio?: number
) => {
  if (type === 'statik_guclendirme') {
    const adv = customAdvanceRatio && customAdvanceRatio > 0 && customAdvanceRatio < 100 ? customAdvanceRatio : 50;
    const half = Math.round(totalAmount * (adv / 100));
    const isPaid1 = ['ilk_taksit_odendi', 'ara_odeme_odendi', 'dosya_bitti_odeme_bekliyor', 'tamami_odendi'].includes(status);
    const isPaid2 = status === 'tamami_odendi';

    return [
      {
        id: 'inst_1',
        name: `1. Taksit (İş Başlangıcı / Peşinat - %${adv})`,
        percentage: adv,
        amount: half,
        isPaid: isPaid1,
        paidAt: isPaid1 ? '2026-08-10' : undefined,
        paymentMethod: 'havale_eft' as const,
      },
      {
        id: 'inst_2',
        name: `2. Taksit (Avan / Detay Proje Teslimi - %${100 - adv})`,
        percentage: 100 - adv,
        amount: Math.max(0, totalAmount - half),
        isPaid: isPaid2,
        paidAt: isPaid2 ? '2026-08-18' : undefined,
        paymentMethod: 'havale_eft' as const,
      },
    ];
  }

  // Riskli Yapı, Orta Katlı Risk ve Performans Raporu için %30 - %30 - %40 taksit planı
  const amt1 = Math.round(totalAmount * 0.3);
  const amt2 = Math.round(totalAmount * 0.3);
  const amt3 = Math.max(0, totalAmount - amt1 - amt2);

  let name1 = '1. Taksit (Numune Günü Belirlendiğinde - %30)';
  let name2 = '2. Taksit (Numuneler Alındığı Gün - %30)';
  let name3 = '3. Taksit (Resmî/Belediye Rapor Onayı - %40)';

  if (type === 'performans_raporu') {
    name1 = '1. Taksit (İş Başlangıcı / Randevu - %30)';
    name2 = '2. Taksit (Saha Numuneleri Alımı - %30)';
    name3 = '3. Taksit (Performans Rapor Teslimi - %40)';
  }

  const isPaid1 = ['ilk_taksit_odendi', 'ara_odeme_odendi', 'dosya_bitti_odeme_bekliyor', 'tamami_odendi'].includes(status);
  const isPaid2 = ['ara_odeme_odendi', 'tamami_odendi'].includes(status);
  const isPaid3 = status === 'tamami_odendi';

  return [
    {
      id: 'inst_1',
      name: name1,
      percentage: 30,
      amount: amt1,
      isPaid: isPaid1,
      paidAt: isPaid1 ? '2026-08-12' : undefined,
      paymentMethod: 'havale_eft' as const,
    },
    {
      id: 'inst_2',
      name: name2,
      percentage: 30,
      amount: amt2,
      isPaid: isPaid2,
      paidAt: isPaid2 ? '2026-08-15' : undefined,
      paymentMethod: 'havale_eft' as const,
    },
    {
      id: 'inst_3',
      name: name3,
      percentage: 40,
      amount: amt3,
      isPaid: isPaid3,
      paidAt: isPaid3 ? '2026-08-19' : undefined,
      paymentMethod: 'havale_eft' as const,
    },
  ];
};

